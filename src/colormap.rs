impl Colormap {
    #[inline]
    pub fn sample(&self, t: f64) -> Rgb<u8> {
        // Fast direct LUT lookup: avoid round() and division operations
        // Multiply by 255 directly and truncate (don't round)
        // Clamp handles values slightly outside [0, 1] (e.g., from gamma correction)
        let i = (t.clamp(0.0, 1.0) * 255.0) as usize;
        Rgb(self.lut[i])
    }

    #[inline]
    pub fn under(&self) -> Rgb<u8> {
        Rgb(self.lut[0])
    }

    #[inline]
    pub fn over(&self) -> Rgb<u8> {
        Rgb(self.lut[self.lut.len() - 1])
    }
}

/* ------------------------------------------------------------------------- */
/*  Lookup helpers                                                            */
/* ------------------------------------------------------------------------- */

pub fn get_colormap(name: &str) -> &'static Colormap {
    let name = name.to_lowercase();
    COLORMAPS
        .iter()
        .copied()
        .find(|c| c.name == name)
        .unwrap_or_else(|| {
            panic!(
                "Unknown colormap '{}'. Available: {}",
                name,
                available_colormaps().join(", ")
            )
        })
}

pub fn available_colormaps() -> Vec<&'static str> {
    COLORMAPS.iter().map(|c| c.name).collect()
}
